// A version's defaults for the player's own Lua settings (tools/openmw/player-defaults.mjs): one generated Orthros data
// root whose PLAYER script gives each value once per player profile, over the engine's registered default only, records
// it, and does nothing on a native simulation peer; the manifest records the root, its entries and its policy.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { installPlayerDefaults, playerDefaultsEntries, playerDefaultsScript, playerDefaultsWithdrawalScript, withdrawPlayerDefaults } from '../tools/openmw/player-defaults.mjs';
import { openmwProblem } from '../src/host/openmw.js';

const DEFAULTS = [
  { group: 'SettingsOMWControls', key: 'alwaysRun', value: true, default: false },
  { group: 'SettingsOMWCameraThirdPerson', key: 'maxDistance', value: 400, default: 800 },
  { group: 'SettingsMyMod', key: 'mode', value: 'modern', default: 'classic' },
];

function fixture(t) {
  const game = fs.mkdtempSync(path.join(os.tmpdir(), 'orthros-player-defaults-'));
  t.after(() => fs.rmSync(game, { recursive: true, force: true }));
  const data = path.join(game, 'versions/one/mods/input-0'); fs.mkdirSync(path.join(data, 'scripts/orthros_qol'), { recursive: true });
  fs.writeFileSync(path.join(data, 'Input.omwscripts'), 'PLAYER: scripts/orthros_qol/input_defaults.lua\n');
  fs.writeFileSync(path.join(data, 'scripts/orthros_qol/input_defaults.lua'), '-- earlier defaults\n');
  const spec = { versions: [{ id: 'one', dir: 'one', openmw: { engine: 'engine', files: ['Game.esm'], mods: [
    { id: 'input', name: 'Input', installed: true, parts: [{ dir: 'mods/input-0', sentinel: 'Input.omwscripts', plugins: ['Input.omwscripts'], archives: [] }] },
  ] } }] };
  fs.writeFileSync(path.join(game, 'manifest.json'), JSON.stringify(spec));
  return { game, data };
}

test('player defaults: checked entries, plain Lua values only', () => {
  assert.deepEqual(playerDefaultsEntries(DEFAULTS), DEFAULTS);
  for (const bad of [[], {}, [{ group: 'Settings X', key: 'a', value: true, default: false }], [{ group: 'S', key: "a'", value: true, default: false }],
    [{ group: 'S', key: 'a', value: true }], [{ group: 'S', key: 'a', value: "x'); os.exit() --", default: 'y' }], [{ group: 'S', key: 'a', value: { x: 1 }, default: 1 }],
    [{ group: 'S', key: 'a', value: 1e21, default: 0 }], [{ group: 'S', key: 'a', value: true, default: true }],
    [{ group: 'S', key: 'a', value: true, default: false }, { group: 'S', key: 'a', value: true, default: false }]])
    assert.throws(() => playerDefaultsEntries(bad), Error, JSON.stringify(bad));
  const lua = playerDefaultsScript(DEFAULTS, 'OrthrosPlayerDefaults');
  assert.match(lua, /^-- Generated by Orthros/);
  assert.match(lua, /if ok and mp\.isSystem and mp\.isSystem\(\) then return \{\} end/, 'nothing on a simulation peer');
  assert.ok(lua.includes("    { 'SettingsOMWControls', 'alwaysRun', true, false },\n"));
  assert.ok(lua.includes("    { 'SettingsOMWCameraThirdPerson', 'maxDistance', 400, 800 },\n"));
  assert.ok(lua.includes("    { 'SettingsMyMod', 'mode', 'modern', 'classic' },\n"));
  assert.ok(lua.includes("storage.playerSection('OrthrosPlayerDefaults')"));
  // (given only over the registered default or an unset value, then recorded whatever the value: never again; the
  // record says which: given, or the player's value kept)
  assert.match(lua, /if not records:get\(record\) then[\s\S]*if current == nil or current == d\[4\] then[\s\S]*records:set\(record, 'given'\)\n            else\n                records:set\(record, 'kept'\)/);
  assert.ok(!lua.includes('records:set(record, true)'));
  assert.match(lua, /engineHandlers = \{ onInit = apply, onLoad = apply \}/);
});

test('player defaults: one generated root, the earlier roots and their records untouched, recorded in the manifest', (t) => {
  const f = fixture(t), before = fs.readFileSync(path.join(f.data, 'scripts/orthros_qol/input_defaults.lua'));
  assert.deepEqual(installPlayerDefaults(f.game, 'one', DEFAULTS),
    { plugin: 'Orthros Player Defaults.omwscripts', script: 'scripts/orthros_player_defaults/player.lua', records: 'OrthrosPlayerDefaults', entries: 3 });
  const root = path.join(f.game, 'versions/one/mods/orthros-player-defaults-0');
  assert.equal(fs.readFileSync(path.join(root, 'Orthros Player Defaults.omwscripts'), 'utf8'), 'PLAYER: scripts/orthros_player_defaults/player.lua\n');
  assert.equal(fs.readFileSync(path.join(root, 'scripts/orthros_player_defaults/player.lua'), 'utf8'), playerDefaultsScript(DEFAULTS, 'OrthrosPlayerDefaults'));
  assert.equal(fs.statSync(path.join(root, 'scripts/orthros_player_defaults/player.lua')).mode & 0o777, 0o644);
  assert.deepEqual(fs.readFileSync(path.join(f.data, 'scripts/orthros_qol/input_defaults.lua')), before);
  const config = JSON.parse(fs.readFileSync(path.join(f.game, 'manifest.json'))).versions[0].openmw;
  assert.equal(openmwProblem(config), null);
  const mod = config.mods.at(-1);
  assert.equal(mod.id, 'orthros-player-defaults');
  assert.deepEqual(mod.playerDefaults, DEFAULTS);
  assert.match(mod.generatedSha256, /^[a-f0-9]{64}$/);
  assert.deepEqual(mod.parts, [{ dir: 'mods/orthros-player-defaults-0', source: 'generated player settings defaults', sentinel: 'Orthros Player Defaults.omwscripts',
    plugins: ['Orthros Player Defaults.omwscripts'], archives: [], files: 2, bytes: mod.parts[0].bytes }]);
  assert.deepEqual(config.mods[0].parts[0].plugins, ['Input.omwscripts'], 'the earlier root keeps its plugin');
  // (never twice, never over an existing root; a second root with its own id, plugin and records)
  const manifest = fs.readFileSync(path.join(f.game, 'manifest.json'));
  assert.throws(() => installPlayerDefaults(f.game, 'one', DEFAULTS), /already installed/);
  assert.throws(() => installPlayerDefaults(f.game, 'one', DEFAULTS, { id: 'Bad Id' }), /Invalid mod id/);
  assert.deepEqual(fs.readFileSync(path.join(f.game, 'manifest.json')), manifest);
  assert.deepEqual(installPlayerDefaults(f.game, 'one', [{ group: 'SettingsMyMod', key: 'extra', value: 2, default: 1 }], { id: 'orthros-player-defaults-2' }),
    { plugin: 'Orthros Player Defaults 2.omwscripts', script: 'scripts/orthros_player_defaults_2/player.lua', records: 'OrthrosPlayerDefaults2', entries: 1 });
});

test('player defaults: withdrawn, the registered default back once where the value was given and is still held', (t) => {
  const lua = playerDefaultsWithdrawalScript(DEFAULTS, 'OrthrosPlayerDefaults');
  assert.match(lua, /^-- Generated by Orthros \(tools\/openmw\/player-defaults\.mjs --withdraw\)/);
  assert.match(lua, /if ok and mp\.isSystem and mp\.isSystem\(\) then return \{\} end/, 'nothing on a simulation peer');
  assert.ok(lua.includes("storage.playerSection('OrthrosPlayerDefaultsRestored')"));
  assert.ok(lua.includes("    { 'SettingsMyMod', 'mode', 'modern', 'classic' },\n"));
  // (only a record saying given - or the older true - and never restored; only over the value it gave)
  assert.match(lua, /if \(done == true or done == 'given'\) and not restored:get\(record\) then[\s\S]*if section:get\(d\[2\]\) == d\[3\] then[\s\S]*section:set\(d\[2\], d\[4\]\)[\s\S]*restored:set\(record, true\)/);

  const f = fixture(t);
  installPlayerDefaults(f.game, 'one', DEFAULTS);
  const root = path.join(f.game, 'versions/one/mods/orthros-player-defaults-0'), script = path.join(root, 'scripts/orthros_player_defaults/player.lua');
  const before = JSON.parse(fs.readFileSync(path.join(f.game, 'manifest.json'))).versions[0].openmw.mods.at(-1);
  assert.throws(() => withdrawPlayerDefaults(f.game, 'one', { id: 'orthros-player-defaults-2' }), /not installed/);
  const out = withdrawPlayerDefaults(f.game, 'one', { because: 'test' });
  assert.equal(out.withdrawn, 3);
  assert.equal(fs.readFileSync(script, 'utf8'), lua);
  assert.equal(fs.statSync(script).mode & 0o777, 0o644);
  const config = JSON.parse(fs.readFileSync(path.join(f.game, 'manifest.json'))).versions[0].openmw;
  assert.equal(openmwProblem(config), null);
  const mod = config.mods.at(-1);
  assert.deepEqual(mod.playerDefaults, []);
  assert.deepEqual(mod.withdrawn.entries, DEFAULTS);
  assert.equal(mod.withdrawn.because, 'test');
  assert.equal(mod.withdrawn.generatedSha256Before, before.generatedSha256);
  assert.equal(out.generatedSha256, mod.generatedSha256);
  assert.notEqual(mod.generatedSha256, before.generatedSha256);
  assert.equal(mod.parts[0].bytes, Buffer.byteLength('PLAYER: scripts/orthros_player_defaults/player.lua\n') + Buffer.byteLength(lua));
  // (once: nothing left to withdraw; and never over files that are not the generated ones)
  assert.throws(() => withdrawPlayerDefaults(f.game, 'one'), /no entries/);
  installPlayerDefaults(f.game, 'one', [{ group: 'SettingsMyMod', key: 'extra', value: 2, default: 1 }], { id: 'orthros-player-defaults-2' });
  fs.appendFileSync(path.join(f.game, 'versions/one/mods/orthros-player-defaults-2-0/scripts/orthros_player_defaults_2/player.lua'), '-- edited\n');
  assert.throws(() => withdrawPlayerDefaults(f.game, 'one', { id: 'orthros-player-defaults-2' }), /differ from the generated/);
});
