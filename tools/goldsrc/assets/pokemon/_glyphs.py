def _parse(rows):
    r = [[c == "1" for c in row] for row in rows.split()]
    while len(r) < 8:
        r.append([False] * 5)
    return np.array(r, dtype=bool)


FONT = {k: _parse(v) for k, v in _F.items()}
KANA = [_parse(v) for v in _K]
CURSOR = "\x7f"


def glyph(ch):
    """5x8 bool array of a character (unknown characters: '?')."""
    return FONT.get(ch, FONT["?"])


def rain_glyphs():
    """The code rain's alphabet: the katakana mirrored left-right, and the digits (some mirrored too)."""
    out = [g[:, ::-1] for g in KANA]
    for i, d in enumerate("0123456789"):
        g = FONT[d]
        out.append(g[:, ::-1] if i % 3 == 1 else g)
    out += [FONT[c] for c in ":=+*<>\"|"]
    return out
