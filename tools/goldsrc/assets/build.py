"""Build the asset archive: python3 -I tools/goldsrc/assets/build.py <out.pk3> [options]

Collects every module tools/goldsrc/assets/pokemon/*.py (names not starting with "_"), calls its
build(out) (out: dict archive path -> bytes, e.g. out["models/pokemon/pikachu.mdl"] = data), checks
the files (.mdl / .spr / .wav parsed and validated, paths relative with forward slashes, no
collisions) and writes a deterministic zip: sorted entries, fixed dates and permissions, deflate.
Prints the manifest (path, size, sha256 prefix).  With no module yet, the archive holds a readme.

Options:
  --only NAME[,NAME]   build only these modules (archive then holds only their files)
  -j N                 modules built in N processes (default: min(4, modules))
  --extract DIR        also write the files under DIR (inspection)
  --render DIR         also render a contact sheet PNG of every .mdl into DIR
  --list               list the modules and exit
"""
import argparse
import hashlib
import importlib
import io
import os
import sys
import time
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from assets import mdl, spr, wav  # noqa: E402

FIXED_DATE = (1980, 1, 1, 0, 0, 0)
README = (b"Half Strike Pokemon assets: generated by tools/goldsrc/assets/build.py (Orthros).\n"
          b"No asset module was present when this archive was built.\n")


def modules():
    d = os.path.join(HERE, "pokemon")
    if not os.path.isdir(d):
        return []
    return sorted(f[:-3] for f in os.listdir(d) if f.endswith(".py") and not f.startswith("_"))


def build_module(name):
    t0 = time.time()
    mod = importlib.import_module(f"assets.pokemon.{name}")
    if not hasattr(mod, "build"):
        raise SystemExit(f"module pokemon/{name}.py has no build(out)")
    out = {}
    mod.build(out)
    return name, out, time.time() - t0


def check_file(path, data):
    """Validate one archive entry; returns a short description."""
    if not isinstance(data, (bytes, bytearray)):
        raise ValueError(f"{path}: content must be bytes")
    if path.startswith("/") or "\\" in path or ".." in path.split("/") or not path:
        raise ValueError(f"{path}: archive paths are relative with forward slashes")
    ext = path.rsplit(".", 1)[-1].lower()
    if ext == "mdl":
        pm = mdl.read(data)
        ntri = sum(len(me.tris) for bp in pm.bodyparts for m in bp.models[:1] for me in m.meshes)
        return f"mdl {len(pm.bones)} bones {len(pm.sequences)} seqs {ntri} tris {len(pm.textures)} tex"
    if ext == "spr":
        s = spr.read(data)
        return f"spr {s['width']}x{s['height']} {len(s['frames'])} frames fmt {s['tex_format']} type {s['type']}"
    if ext == "wav":
        x, rate, bits, ch = wav.read(data)
        if ch != 1 or rate != 22050 or bits not in (8, 16):
            raise ValueError(f"{path}: wav must be mono 22050 Hz 8/16-bit (got {ch} ch {rate} Hz {bits} bit)")
        return f"wav {len(x) / rate:.2f}s {bits}-bit"
    return ext


def write_zip(path, files):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name in sorted(files):
            zi = zipfile.ZipInfo(name, date_time=FIXED_DATE)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.create_system = 3
            zi.external_attr = 0o644 << 16
            z.writestr(zi, bytes(files[name]), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    tmp = path + ".tmp"
    with open(tmp, "wb") as f:
        f.write(buf.getvalue())
    os.replace(tmp, path)
    return len(buf.getvalue())


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out", nargs="?")
    ap.add_argument("--only")
    ap.add_argument("-j", type=int, default=None)
    ap.add_argument("--extract")
    ap.add_argument("--render")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args(argv)
    names = modules()
    if a.list:
        print("\n".join(names) if names else "(no asset module)")
        return 0
    if not a.out:
        ap.error("output path required")
    if a.only:
        wanted = a.only.split(",")
        missing = [w for w in wanted if w not in names]
        if missing:
            raise SystemExit(f"unknown module(s): {missing}; available: {names}")
        names = wanted
    files, owner = {}, {}
    results = []
    jobs = a.j if a.j is not None else min(4, max(1, len(names)))
    if jobs > 1 and len(names) > 1:
        import multiprocessing as mp
        with mp.get_context("fork").Pool(jobs) as pool:
            results = pool.map(build_module, names)
    else:
        results = [build_module(n) for n in names]
    for name, out, dt in results:
        print(f"module {name}: {len(out)} files in {dt:.1f}s", file=sys.stderr)
        for p, data in out.items():
            p = p.replace("\\", "/")
            if p.lower() in owner:
                raise SystemExit(f"{p} produced by both {owner[p.lower()]} and {name}")
            owner[p.lower()] = name
            files[p] = data
    if not files:
        files["pokemon_readme.txt"] = README
    lines = []
    total = 0
    for p in sorted(files):
        desc = check_file(p, files[p])
        total += len(files[p])
        lines.append(f"{len(files[p]):>9}  {hashlib.sha256(files[p]).hexdigest()[:12]}  {p}  ({desc})")
    zsize = write_zip(a.out, files)
    print("\n".join(lines))
    print(f"{len(files)} files, {total} bytes, archive {a.out} {zsize} bytes")
    if a.extract:
        for p, data in files.items():
            dst = os.path.join(a.extract, *p.split("/"))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "wb") as f:
                f.write(data)
    if a.render:
        from assets import render
        os.makedirs(a.render, exist_ok=True)
        for p in sorted(files):
            if p.lower().endswith(".mdl"):
                pm = mdl.read(files[p])
                dst = os.path.join(a.render, os.path.basename(p)[:-4] + ".png")
                render.contact_sheet(pm, frames=6, cell=200).save(dst)
                print(f"rendered {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
