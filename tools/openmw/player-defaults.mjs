// A version's defaults for the player's own Lua settings (OpenMW's Options → Scripts pages: OMWControls, OMWCamera, a
// mod's), given once. Those settings live in the player's storage (player_storage.bin, the player's profile), not in
// settings.cfg: the manifest's openmw.settings cannot reach them. The generated data root holds one PLAYER script that,
// on a browser client (never on a native simulation peer), sets each listed value once per player profile, only over
// the value the engine registers by default, and records it: a later choice of the player's (the Options page, a toggle
// key), or a value already moved off that default, is never overwritten. Each entry has its own record, so a later
// root may add entries; never remove this one (the records name its entries). Each record says what was done:
// 'given' (the value set) or 'kept' (the player's value already off the default); roots generated before 2026-10-30
// recorded true for both.
// Withdrawing: the root's script replaced by one that gives the registered default back, once, to each profile whose
// record says the value was given ('given', or true: those older records cannot tell given from kept) and that still
// holds it; a value the player moved since is left alone. The manifest keeps the entries under `withdrawn`.
// Usage: node tools/openmw/player-defaults.mjs <game-folder> <version-id> <defaults.json> [--id <mod-id>]
//        node tools/openmw/player-defaults.mjs <game-folder> <version-id> --withdraw [--id <mod-id>] [--because <text>]
//   defaults.json: [{ "group": "SettingsOMWControls", "key": "alwaysRun", "value": true, "default": false }, ...]
//     group: the settings group's storage section (I.Settings.registerGroup key); default: its registered default
//   --id: the generated root's mod id (default orthros-player-defaults); its plugin is named after it
//     (Orthros Player Defaults.omwscripts), its script goes to scripts/<id with _>/player.lua
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';

const DEFAULT_ID = 'orthros-player-defaults';
const NAME = /^[A-Za-z][A-Za-z0-9_]{0,63}$/;
// (a value a settings renderer stores: a boolean, a number, a plain word or phrase)
const TEXT = /^[A-Za-z0-9 ._,-]{0,64}$/;
const luaValue = (v) => typeof v === 'boolean' ? String(v) : typeof v === 'number' && Number.isFinite(v) && /^-?[0-9.]+$/.test(String(v)) ? String(v)
  : typeof v === 'string' && TEXT.test(v) ? `'${v}'` : null;

/** The entries of a defaults file, checked: [{ group, key, value, default }]. */
export function playerDefaultsEntries(list) {
  if (!Array.isArray(list) || !list.length || list.length > 256) throw new Error('Expected a non-empty list of player defaults');
  const seen = new Set();
  return list.map((d) => {
    if (!d || typeof d !== 'object' || !NAME.test(d.group ?? '') || !NAME.test(d.key ?? '')) throw new Error(`Bad player default ${JSON.stringify(d)}`);
    if (luaValue(d.value) === null || luaValue(d.default) === null) throw new Error(`${d.group}/${d.key}: value and default must be booleans, numbers or plain words`);
    if (d.value === d.default) throw new Error(`${d.group}/${d.key}: the value is already the engine's default`);
    if (seen.has(`${d.group}/${d.key}`)) throw new Error(`${d.group}/${d.key} listed twice`);
    seen.add(`${d.group}/${d.key}`);
    return { group: d.group, key: d.key, value: d.value, default: d.default };
  });
}

/** The PLAYER script giving `entries` once, its records in storage section `records`. */
export function playerDefaultsScript(entries, records) {
  const rows = entries.map((e) => `    { '${e.group}', '${e.key}', ${luaValue(e.value)}, ${luaValue(e.default)} },`).join('\n');
  return `-- Generated by Orthros (tools/openmw/player-defaults.mjs): the version's player settings defaults, given once.
-- Each entry is set once per player profile, only over the engine's registered default, and recorded in the
-- ${records} section: a later choice of the player's is never overwritten. Never on a simulation peer.
local ok, mp = pcall(require, 'openmw.mp')
if ok and mp.isSystem and mp.isSystem() then return {} end
local storage = require('openmw.storage')
local records = storage.playerSection('${records}')
-- { settings group, key, value, the engine's default }
local DEFAULTS = {
${rows}
}
local function apply()
    local given = {}
    for _, d in ipairs(DEFAULTS) do
        local record = d[1] .. '/' .. d[2]
        if not records:get(record) then
            local section = storage.playerSection(d[1])
            local current = section:get(d[2])
            if current == nil or current == d[4] then
                section:set(d[2], d[3])
                given[#given + 1] = record
                records:set(record, 'given')
            else
                records:set(record, 'kept')
            end
        end
    end
    if #given > 0 then print('[orthros] player defaults given: ' .. table.concat(given, ', ')) end
end
return { engineHandlers = { onInit = apply, onLoad = apply } }
`;
}

/** The PLAYER script withdrawing `entries` a root gave (records in section `records`): the registered default back once. */
export function playerDefaultsWithdrawalScript(entries, records) {
  const rows = entries.map((e) => `    { '${e.group}', '${e.key}', ${luaValue(e.value)}, ${luaValue(e.default)} },`).join('\n');
  return `-- Generated by Orthros (tools/openmw/player-defaults.mjs --withdraw): this root's entries are withdrawn. A profile
-- whose ${records} record says the value was given ('given'; true, from a root generated before 2026-10-30, may
-- also mean the player's own value was kept) and that still holds it gets the engine's registered default back, once
-- (recorded in ${records}Restored). A value the player moved since is left alone. Never on a simulation peer.
-- Never remove the root: its records name its entries.
local ok, mp = pcall(require, 'openmw.mp')
if ok and mp.isSystem and mp.isSystem() then return {} end
local storage = require('openmw.storage')
local records = storage.playerSection('${records}')
local restored = storage.playerSection('${records}Restored')
-- { settings group, key, the value this root gave, the engine's default }
local WITHDRAWN = {
${rows}
}
local function apply()
    local back = {}
    for _, d in ipairs(WITHDRAWN) do
        local record = d[1] .. '/' .. d[2]
        local done = records:get(record)
        if (done == true or done == 'given') and not restored:get(record) then
            local section = storage.playerSection(d[1])
            if section:get(d[2]) == d[3] then
                section:set(d[2], d[4])
                back[#back + 1] = record
            end
            restored:set(record, true)
        end
    end
    if #back > 0 then print('[orthros] player defaults withdrawn: ' .. table.concat(back, ', ')) end
end
return { engineHandlers = { onInit = apply, onLoad = apply } }
`;
}

const rootNames = (id) => {
  const title = id.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
  return { title, plugin: `${title}.omwscripts`, ns: `scripts/${id.replaceAll('-', '_')}`, records: title.replaceAll(' ', '') };
};

/** Generates the root in the version and records it in its manifest (installed, with its entries). */
export function installPlayerDefaults(folder, versionId, list, { id = DEFAULT_ID } = {}) {
  const entries = playerDefaultsEntries(list);
  // (the manifest's mod id rule, src/host/openmw.js MOD_ID)
  if (!/^[a-z0-9][a-z0-9-]{0,54}$/.test(id)) throw new Error('Invalid mod id');
  const game = fs.realpathSync(folder), file = path.join(game, 'manifest.json');
  const spec = JSON.parse(fs.readFileSync(file, 'utf8')), version = spec.versions.find((v) => v.id === versionId);
  const mods = version?.openmw?.mods;
  if (!mods) throw new Error(`No OpenMW version with mods: ${versionId}`);
  if (mods.some((m) => m.id === id)) throw new Error(`${id} is already installed`);
  const { plugin, ns, records } = rootNames(id);
  if (mods.some((m) => (m.parts ?? []).some((p) => p.plugins.some((n) => n.toLowerCase() === plugin.toLowerCase())))) throw new Error(`${plugin} is another root's plugin`);
  const versionDir = fs.realpathSync(path.join(game, 'versions', version.dir));
  for (const part of mods.flatMap((m) => m.parts ?? []))
    if (fs.existsSync(path.join(versionDir, part.dir, ns))) throw new Error(`${ns} already exists in ${part.dir}; choose another --id`);
  const dir = `mods/${id}-0`, dest = path.join(versionDir, dir);
  if (fs.existsSync(dest)) throw new Error(`${dest} already exists; no overwrite`);
  const files = new Map([[plugin, `PLAYER: ${ns}/player.lua\n`], [`${ns}/player.lua`, playerDefaultsScript(entries, records)]]);
  const hash = createHash('sha256');
  fs.mkdirSync(dest, { recursive: true });
  for (const [name, text] of files) {
    fs.mkdirSync(path.dirname(path.join(dest, name)), { recursive: true });
    fs.writeFileSync(path.join(dest, name), text, { flag: 'wx' }); hash.update(name).update('\0').update(text);
  }
  // (readable by the services' users whatever the umask, as install-mod.mjs leaves a mod)
  for (const p of [dest, path.join(dest, 'scripts'), path.join(dest, ns)]) fs.chmodSync(p, 0o755);
  for (const name of files.keys()) fs.chmodSync(path.join(dest, name), 0o644);
  mods.push({ id, name: id === DEFAULT_ID ? 'Player settings defaults (Orthros)' : `Player settings defaults (Orthros, ${id})`,
    installed: true, installedAt: new Date().toISOString(), generatedSha256: hash.digest('hex'),
    playerDefaults: entries, policy: `Once per player profile, only over the engine's registered default, recorded in storage section ${records}; a player's later choice is kept; never on a simulation peer`,
    parts: [{ dir, source: 'generated player settings defaults', sentinel: plugin, plugins: [plugin], archives: [],
      files: files.size, bytes: [...files.values()].reduce((sum, s) => sum + Buffer.byteLength(s), 0) }] });
  fs.writeFileSync(file + '.new', JSON.stringify(spec, null, 2) + '\n'); fs.renameSync(file + '.new', file);
  return { plugin, script: `${ns}/player.lua`, records, entries: entries.length };
}

/**
 * Withdraws every entry of an installed root: its script replaced by the withdrawal script (playerDefaultsWithdrawalScript),
 * the manifest's entry moved to `withdrawn` (playerDefaults emptied), its hash and sizes updated. The root stays.
 */
export function withdrawPlayerDefaults(folder, versionId, { id = DEFAULT_ID, because = null } = {}) {
  const game = fs.realpathSync(folder), file = path.join(game, 'manifest.json');
  const spec = JSON.parse(fs.readFileSync(file, 'utf8')), version = spec.versions.find((v) => v.id === versionId);
  const mod = version?.openmw?.mods?.find((m) => m.id === id);
  if (!mod) throw new Error(`${id} is not installed in ${versionId}`);
  if (!mod.playerDefaults?.length) throw new Error(`${id} has no entries to withdraw`);
  if (because !== null && (typeof because !== 'string' || !because.trim())) throw new Error('Expected a reason');
  const entries = playerDefaultsEntries(mod.playerDefaults), { plugin, ns, records } = rootNames(id);
  const part = mod.parts?.[0];
  if (!part || part.sentinel !== plugin) throw new Error(`${id} is not a generated player defaults root`);
  const dest = path.join(fs.realpathSync(path.join(game, 'versions', version.dir)), part.dir);
  const pluginText = fs.readFileSync(path.join(dest, plugin), 'utf8'), scriptPath = path.join(dest, ns, 'player.lua');
  const current = fs.readFileSync(scriptPath, 'utf8');
  const hashOf = (texts) => { const h = createHash('sha256'); for (const [n, t] of texts) h.update(n).update('\0').update(t); return h.digest('hex'); };
  if (hashOf([[plugin, pluginText], [`${ns}/player.lua`, current]]) !== mod.generatedSha256) throw new Error(`${id}: its files differ from the generated ones; no overwrite`);
  const script = playerDefaultsWithdrawalScript(entries, records);
  fs.writeFileSync(scriptPath + '.new', script, { mode: 0o644 }); fs.chmodSync(scriptPath + '.new', 0o644); fs.renameSync(scriptPath + '.new', scriptPath);
  mod.withdrawn = { at: new Date().toISOString(), entries, ...(because ? { because } : {}),
    generatedSha256Before: mod.generatedSha256 };
  mod.playerDefaults = [];
  mod.generatedSha256 = hashOf([[plugin, pluginText], [`${ns}/player.lua`, script]]);
  mod.policy = `Withdrawn: the registered default given back once to a profile whose record in storage section ${records} says the value was given and that still holds it (recorded in ${records}Restored); a player's later choice is kept; never on a simulation peer`;
  part.bytes = Buffer.byteLength(pluginText) + Buffer.byteLength(script);
  fs.writeFileSync(file + '.new', JSON.stringify(spec, null, 2) + '\n'); fs.renameSync(file + '.new', file);
  return { script: `${ns}/player.lua`, records, withdrawn: entries.length, generatedSha256: mod.generatedSha256 };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2), at = args.indexOf('--id'), opts = {};
  if (at >= 0) { opts.id = args[at + 1]; args.splice(at, 2); }
  const withdraw = args.indexOf('--withdraw');
  if (withdraw >= 0) {
    args.splice(withdraw, 1);
    const by = args.indexOf('--because');
    if (by >= 0) { opts.because = args[by + 1]; args.splice(by, 2); }
    const [folder, version] = args;
    if (!folder || !version || args.length !== 2 || (at >= 0 && !opts.id)) throw new Error('Expected game folder and version id');
    console.log(JSON.stringify(withdrawPlayerDefaults(folder, version, opts)));
    process.exit(0);
  }
  const [folder, version, list] = args;
  if (!folder || !version || !list || (at >= 0 && !opts.id)) throw new Error('Expected game folder, version id and defaults file');
  console.log(JSON.stringify(installPlayerDefaults(folder, version, JSON.parse(fs.readFileSync(list, 'utf8')), opts)));
}
